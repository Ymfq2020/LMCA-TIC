def export_chapter3_reported_results(output_dir: str | Path) -> dict[str, object]:
    target = ensure_dir(output_dir)
    manifest_tables: list[dict[str, object]] = []
    all_rows = list(iter_chapter3_reported_rows())
    write_jsonl(target / "reported_results.jsonl", all_rows)

    for table_id, spec in CHAPTER3_REPORTED_TABLES.items():
        rows = list(_enriched_rows(table_id, spec))
        fieldnames = COMMON_FIELDNAMES + list(spec["fieldnames"])
        csv_path = target / f"{table_id}.csv"
        json_path = target / f"{table_id}.json"
        _write_csv(csv_path, rows, fieldnames)
        write_json(
            json_path,
            {
                "table_id": table_id,
                "paper_table_number": spec["paper_table_number"],
                "paper_table_label": spec["paper_table_label"],
                "paper_table_title": spec["paper_table_title"],
                "provenance": PROVENANCE,
                "source_document": SOURCE_DOCUMENT,
                "source_note": SOURCE_NOTE,
                "rows": rows,
            },
        )
        manifest_tables.append(
            {
                "table_id": table_id,
                "paper_table_number": spec["paper_table_number"],
                "paper_table_label": spec["paper_table_label"],
                "paper_table_title": spec["paper_table_title"],
                "row_count": len(rows),
                "csv": csv_path.name,
                "json": json_path.name,
            }
        )

    manifest = {
        "chapter": 3,
        "provenance": PROVENANCE,
        "source_document": SOURCE_DOCUMENT,
        "source_note": SOURCE_NOTE,
        "reported_results_jsonl": "reported_results.jsonl",
        "tables": manifest_tables,
    }
    write_json(target / "manifest.json", manifest)
    return manifest


def audit_chapter3_assets(
    experiment_root: str | Path = "outputs/experiments",
    reported_root: str | Path = "paper_reported_results/chapter3",
) -> dict[str, object]:
    experiment_root_path = Path(experiment_root)
    reported_root_path = Path(reported_root)

    reported_checks = [
        _check_path(reported_root_path, "manifest", Path("manifest.json")),
        _check_path(reported_root_path, "reported_results_jsonl", Path("reported_results.jsonl")),
    ]
    for table_id in CHAPTER3_REPORTED_TABLES:
        reported_checks.append(_check_path(reported_root_path, table_id, Path(f"{table_id}.csv")))
        reported_checks.append(_check_path(reported_root_path, f"{table_id}_json", Path(f"{table_id}.json")))

    runtime_checks = [
        _check_path(experiment_root_path, check_name, Path(relative_path))
        for check_name, relative_path in CHAPTER3_RUNTIME_REQUIREMENTS
    ]
    return {
        "reported_root": str(reported_root_path),
        "experiment_root": str(experiment_root_path),
        "reported_assets": reported_checks,
        "runtime_assets": runtime_checks,
        "reported_ok": all(check["exists"] for check in reported_checks),
        "runtime_ok": all(check["exists"] for check in runtime_checks),
    }


def iter_chapter3_reported_rows() -> Iterable[dict[str, object]]:
    for table_id, spec in CHAPTER3_REPORTED_TABLES.items():
        yield from _enriched_rows(table_id, spec)


def _enriched_rows(table_id: str, spec: dict[str, object]) -> Iterable[dict[str, object]]:
    del table_id
    for row in spec["rows"]:
        yield {
            "provenance": PROVENANCE,
            "reported_in_manuscript": True,
            "source_document": SOURCE_DOCUMENT,
            "source_note": SOURCE_NOTE,
            "paper_table_number": spec["paper_table_number"],
            "paper_table_label": spec["paper_table_label"],
            "paper_table_title": spec["paper_table_title"],
            **row,
        }


def _check_path(root: Path, name: str, relative_path: Path) -> dict[str, object]:
    target = root / relative_path
    return {
        "name": name,
        "relative_path": str(relative_path),
        "exists": target.exists(),
    }


def _write_csv(path: Path, rows: list[dict[str, object]], fieldnames: list[str]) -> None:
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
